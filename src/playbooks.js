function normalizeTitle(title) {
  return String(title ?? "").trim() || "Applied AI project";
}

export function resolvePlaybook(title) {
  const projectTitle = normalizeTitle(title);
  const text = projectTitle.toLowerCase();

  if (/(sentiment|sentimental|emotion|opinion mining|whisper|polarity)/.test(text)) {
    return { ...sentimentAnalysis, title: projectTitle };
  }
  if (/(image|vision|classif|classifier|cnn|object detection|recognition|segmentation)/.test(text)) {
    return { ...imageClassification, title: projectTitle };
  }

  return {
    ...generic,
    title: projectTitle,
    overview: generic.overview.replaceAll("{{PROJECT}}", projectTitle),
    brief: generic.brief.replaceAll("{{PROJECT}}", projectTitle),
  };
}

export function projectKeyFor(title) {
  return resolvePlaybook(title).key;
}

export function playbookForStudent(student) {
  return resolvePlaybook(student?.projectTitle);
}

